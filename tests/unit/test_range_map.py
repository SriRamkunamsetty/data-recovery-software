"""Unit tests for RangeStatusMap interval splitting, coalescing, and persistence."""

import json
from pathlib import Path

from recoverx.domain.imaging import BlockRange, SectorStatus
from recoverx.infrastructure.storage.range_map import RangeStatusMap


def test_range_map_initialization() -> None:
    rmap = RangeStatusMap(total_sectors=1000, sector_size=512)
    assert rmap.total_sectors == 1000
    assert rmap.sector_size == 512
    assert len(rmap.ranges) == 1
    expected_range = BlockRange(start_sector=0, sector_count=1000, status=SectorStatus.NON_TRIED)
    assert rmap.ranges[0] == expected_range
    assert not rmap.is_all_finished
    assert rmap.finished_sectors_count == 0
    assert rmap.bad_sectors_count == 0


def test_range_map_split_and_coalesce() -> None:
    rmap = RangeStatusMap(total_sectors=100)

    # 1. Update sectors 10..30 to FINISHED -> splits into 3 ranges
    rmap.update_range(start_sector=10, sector_count=20, new_status=SectorStatus.FINISHED)
    assert len(rmap.ranges) == 3
    assert rmap.ranges[0] == BlockRange(0, 10, SectorStatus.NON_TRIED)
    assert rmap.ranges[1] == BlockRange(10, 20, SectorStatus.FINISHED)
    assert rmap.ranges[2] == BlockRange(30, 70, SectorStatus.NON_TRIED)
    assert rmap.finished_sectors_count == 20

    # 2. Update sectors 0..10 to FINISHED -> coalesces with [10..30, +] -> [0..30, +]
    rmap.update_range(start_sector=0, sector_count=10, new_status=SectorStatus.FINISHED)
    assert len(rmap.ranges) == 2
    assert rmap.ranges[0] == BlockRange(0, 30, SectorStatus.FINISHED)
    assert rmap.ranges[1] == BlockRange(30, 70, SectorStatus.NON_TRIED)
    assert rmap.finished_sectors_count == 30

    # 3. Update sectors 30..100 to FINISHED -> coalesces completely -> [0..100, +]
    rmap.update_range(start_sector=30, sector_count=70, new_status=SectorStatus.FINISHED)
    assert len(rmap.ranges) == 1
    assert rmap.ranges[0] == BlockRange(0, 100, SectorStatus.FINISHED)
    assert rmap.is_all_finished is True


def test_range_map_bad_sector_marking() -> None:
    rmap = RangeStatusMap(total_sectors=50)
    rmap.update_range(0, 50, SectorStatus.FINISHED)

    # Mark sector 15 as BAD
    rmap.update_range(15, 1, SectorStatus.BAD, error_message="I/O Error")
    assert rmap.bad_sectors_count == 1
    assert rmap.finished_sectors_count == 49
    assert not rmap.is_all_finished

    bad_ranges = rmap.get_ranges_by_status(SectorStatus.BAD)
    assert len(bad_ranges) == 1
    assert bad_ranges[0].start_sector == 15
    assert bad_ranges[0].sector_count == 1
    assert bad_ranges[0].error_message == "I/O Error"


def test_range_map_serialization_round_trip(tmp_path: Path) -> None:
    rmap = RangeStatusMap(total_sectors=500, sector_size=4096)
    rmap.update_range(0, 200, SectorStatus.FINISHED)
    rmap.update_range(200, 5, SectorStatus.BAD, error_message="CRC Error")
    rmap.update_range(205, 95, SectorStatus.NON_SCRAPED)

    map_path = tmp_path / "test.map.json"
    rmap.save_file(map_path)

    loaded = RangeStatusMap.load_file(map_path)
    assert loaded.total_sectors == rmap.total_sectors
    assert loaded.sector_size == rmap.sector_size
    assert loaded.finished_sectors_count == rmap.finished_sectors_count
    assert loaded.bad_sectors_count == rmap.bad_sectors_count
    assert len(loaded.ranges) == len(rmap.ranges)


def test_range_map_export_bad_sectors_and_ddrescue(tmp_path: Path) -> None:
    rmap = RangeStatusMap(total_sectors=100, sector_size=512)
    rmap.update_range(0, 50, SectorStatus.FINISHED)
    rmap.update_range(50, 2, SectorStatus.BAD, error_message="Bad sector")

    bad_path = tmp_path / "bad.json"
    rmap.export_bad_sectors_json(bad_path)
    with open(bad_path, encoding="utf-8") as f:
        bad_data = json.load(f)
    assert len(bad_data) == 1
    assert bad_data[0]["start_sector"] == 50
    assert bad_data[0]["sector_count"] == 2
    assert bad_data[0]["start_offset"] == 50 * 512
    assert bad_data[0]["error_message"] == "Bad sector"

    ddrescue_path = tmp_path / "test.map"
    rmap.export_ddrescue_mapfile(ddrescue_path, current_pos=52)
    content = ddrescue_path.read_text(encoding="utf-8")
    assert "# Mapfile. Generated by RecoverX" in content
    assert "0x00006400  0x00000400  -" in content  # 50 * 512 = 0x6400, size 2 * 512 = 0x400
